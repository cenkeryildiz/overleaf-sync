// Glue for the existing authenticated CE+ compile controller; the Rust worker owns preview state.
import logger from '@overleaf/logger';
import { spawn } from 'node:child_process';
import { createInterface } from 'node:readline';
import { randomBytes, createHash } from 'node:crypto';
import { mkdtemp, rm } from 'node:fs/promises';
import ProjectEntityHandler from '../Project/ProjectEntityHandler.mjs';
import ClsiManager from './ClsiManager.mjs';
import SessionManager from '../Authentication/SessionManager.mjs';

const sessions = new Map();
function close(token) {
  const session = sessions.get(token); if (!session) return;
  sessions.delete(token); clearTimeout(session.timer); session.child?.kill('SIGTERM');
}
function expiry(session) { clearTimeout(session.timer); session.timer = setTimeout(() => close(session.token), 10 * 60 * 1000); session.timer.unref(); }
function ask(session, request) {
  if (session.busy) throw Error('Preview request already running');
  session.busy = true;
  return new Promise((resolve, reject) => {
    const timer = setTimeout(() => { session.pending = null; close(session.token); reject(Error('Preview timed out')); }, 35000);
    session.pending = { resolve: value => { clearTimeout(timer); session.busy = false; resolve(value); }, reject: error => { clearTimeout(timer); session.busy = false; reject(error); } };
    session.child.stdin.write(JSON.stringify(request) + '\n', error => { if (error) session.pending?.reject(Error('Preview unavailable')); });
  });
}
async function snapshot(projectId, userId, body, loadAssets = true) {
  if (!/^[a-f0-9]{24}$/.test(body.docId) || typeof body.text !== 'string' || body.text.length > 2_000_000) throw Error('Invalid document');
  const request = await ClsiManager.promises.buildDocumentConversionRequest(projectId, userId, { compileGroup: 'standard' });
  const compile = request.compile;
  if (!compile || !Array.isArray(compile.resources) || compile.resources.length > 1000) throw Error('Project snapshot unavailable');
  const docs = await ProjectEntityHandler.promises.getAllDocs(projectId);
  const entry = Object.entries(docs).find(([, doc]) => String(doc._id) === body.docId);
  if (!entry) throw Error('Document is not in this project');
  const active = entry[0].replace(/^\//, '');
  const fingerprint = createHash('sha256').update(JSON.stringify([compile.rootResourcePath, compile.resources.filter(r => r.path !== active).map(r => [r.path, r.content ?? r.url])])).digest('hex');
  const resources = []; let size = 0;
  for (const resource of loadAssets ? compile.resources : []) {
    if (typeof resource.content === 'string') {
      size += Buffer.byteLength(resource.content); resources.push({ path: resource.path, content: resource.content });
    } else {
      // URLs are generated by native history helpers, never accepted from the caller.
      const response = await fetch(resource.url, { signal: AbortSignal.timeout(10000), redirect: 'error' });
      if (!response.ok || Number(response.headers.get('content-length')) > 20 * 1024 * 1024) throw Error('Project asset unavailable');
      const reader = response.body.getReader(); const chunks = []; let bytes = 0;
      while (true) { const { done, value } = await reader.read(); if (done) break; bytes += value.byteLength; if (bytes > 20 * 1024 * 1024) { await reader.cancel(); throw Error('Asset exceeds preview limit'); } chunks.push(value); }
      size += bytes; resources.push({ path: resource.path, data: Buffer.concat(chunks, bytes).toString('base64') });
    }
    if (size > 64 * 1024 * 1024) throw Error('Project exceeds preview limit');
  }
  return { op: 'start', fingerprint, main: compile.rootResourcePath, active, resources, text: body.text, line: body.line };
}
export async function livePreview(req, res) {
  res.set('Cache-Control', 'no-store');
  const userId = SessionManager.getLoggedInUserId(req.session)?.toString();
  const projectId = String(req.params.Project_id), body = req.body?.livePreview;
  if (!userId || !/^[a-f0-9]{24}$/.test(userId) || !/^[a-f0-9]{24}$/.test(projectId)) return res.sendStatus(401);
  if (!body || !['start', 'edit', 'jump', 'refresh', 'close'].includes(body.op)) return res.sendStatus(400);
  if (['start', 'edit', 'refresh'].includes(body.op) && (!Number.isInteger(body.line) || body.line < 1 || body.line > 1_000_000)) return res.sendStatus(400);
  let session, stage = 'request';
  try {
    if (body.op === 'start') {
      if (sessions.size >= 4 || [...sessions.values()].filter(s => s.userId === userId).length >= 2) return res.status(429).json({ error: 'Live preview is busy. PDF remains available.' });
      const token = randomBytes(24).toString('hex');
      const slot = [0, 1, 2, 3].find(slot => ![...sessions.values()].some(s => s.slot === slot));
      session = { token, userId, projectId, slot, busy: false }; sessions.set(token, session);
      stage = 'workspace';
      const work = await mkdtemp('/var/lib/overleaf/data/live-preview-');
      stage = 'worker';
      const child = spawn('/opt/texpresso/bin/overleaf-live-preview', [work], { stdio: ['pipe', 'pipe', 'ignore'] });
      Object.assign(session, { child, work }); expiry(session);
      child.on('error', () => { session.pending?.reject(Error('Preview unavailable')); close(token); });
      child.on('exit', () => { session.pending?.reject(Error('Preview stopped')); close(token); rm(work, { recursive: true, force: true }).catch(() => {}); });
      createInterface({ input: child.stdout }).on('line', line => {
        try { const value = JSON.parse(line); const pending = session.pending; session.pending = null; pending?.resolve(value); } catch { session.pending?.reject(Error('Invalid preview response')); close(token); }
      });
      stage = 'snapshot';
      const start = await snapshot(projectId, userId, body);
      Object.assign(session, { fingerprint: start.fingerprint, docId: body.docId });
      stage = 'render';
      const result = await ask(session, { ...start, uid: 61000 + slot });
      if (!result.ok) { session.failure = result.error; throw Error('Preview unavailable'); }
      return res.json({ ...result, token, active: start.active });
    }
    session = sessions.get(body.token);
    if (!session || session.projectId !== projectId || session.userId !== userId) return res.sendStatus(404);
    expiry(session);
    if (body.op === 'close') { close(body.token); return res.sendStatus(204); }
    if (body.op === 'refresh') {
      const fresh = await snapshot(projectId, userId, { docId: session.docId, text: '', line: 1 }, false);
      if (fresh.fingerprint !== session.fingerprint) { close(body.token); return res.json({ restart: true }); }
      return res.json({ restart: false });
    }
    if (body.op === 'jump') {
      if (![body.revision, body.page].every(n => Number.isSafeInteger(n) && n >= 0) || ![body.x, body.y].every(n => Number.isFinite(n) && n >= 0 && n < 20000)) return res.sendStatus(400);
      const result = await ask(session, { op: 'jump', revision: body.revision, page: body.page, x: body.x, y: body.y });
      if (!result.ok) throw Error('Source location unavailable');
      return res.json(result.jump);
    }
    if (![body.base, body.revision, body.offset, body.remove].every(n => Number.isSafeInteger(n) && n >= 0 && n < 1_000_000_000) || typeof body.insert !== 'string' || body.insert.length > 2_000_000) return res.sendStatus(400);
    const result = await ask(session, { op: 'edit', base: body.base, revision: body.revision, offset: body.offset, remove: body.remove, insert: body.insert, line: body.line });
    if (!result.ok) throw Error(result.error || 'Preview unavailable');
    return res.json(result);
  } catch (error) {
    logger.warn({ stage, failure: session?.failure, category: error.name }, 'Live preview unavailable');
    if (session) close(session.token);
    return res.status(503).json({ error: 'Live preview unavailable. The normal PDF compiler remains available.' });
  }
}
